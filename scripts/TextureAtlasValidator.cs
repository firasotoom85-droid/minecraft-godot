using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Godot;

namespace Minecraft;

public enum TextureValidationSeverity
{
    Info,
    Warning,
    Error,
}

public readonly record struct TextureValidationIssue(
        TextureValidationSeverity Severity, string Code, string Message);

internal readonly record struct AtlasBlockMapping(BlockId Id, string Name, int[] FaceTiles);

internal readonly record struct AtlasItemMapping(
        ItemId Id, BlockId? Block, bool UsesAtlasIcon, Rect2 IconRegion, bool RoundTrips);

/// <summary>
/// Immutable result of an explicit procedural texture/atlas audit. It is a
/// development report, not a runtime resource and is never consulted by meshing.
/// </summary>
public sealed class TextureValidationReport
{
    private readonly List<TextureValidationIssue> _issues;
    private readonly List<AtlasBlockMapping> _blocks;
    private readonly List<AtlasItemMapping> _items;
    private readonly List<TextureAtlasTileSummary> _tiles;

    internal TextureValidationReport(
            int atlasColumns, int tilePixels, int atlasWidth, int atlasHeight,
            int referencedTiles, int paintedTiles, int orphanedPaintedTiles,
            int placeableItems, int tileArrayLayers, bool tileArrayHasMipmaps,
            List<TextureValidationIssue> issues, List<AtlasBlockMapping> blocks,
            List<AtlasItemMapping> items, List<TextureAtlasTileSummary> tiles)
    {
        AtlasColumns = atlasColumns;
        TilePixels = tilePixels;
        AtlasWidth = atlasWidth;
        AtlasHeight = atlasHeight;
        ReferencedTiles = referencedTiles;
        PaintedTiles = paintedTiles;
        OrphanedPaintedTiles = orphanedPaintedTiles;
        PlaceableItems = placeableItems;
        TileArrayLayers = tileArrayLayers;
        TileArrayHasMipmaps = tileArrayHasMipmaps;
        _issues = issues;
        _blocks = blocks;
        _items = items;
        _tiles = tiles;
    }

    public int AtlasColumns { get; }
    public int TilePixels { get; }
    public int AtlasWidth { get; }
    public int AtlasHeight { get; }
    public int TileCount => AtlasColumns * AtlasColumns;
    public int ReferencedTiles { get; }
    public int PaintedTiles { get; }
    public int OrphanedPaintedTiles { get; }
    public int PlaceableItems { get; }
    public int TileArrayLayers { get; }
    public bool TileArrayHasMipmaps { get; }
    public int ErrorCount => _issues.Count(issue => issue.Severity == TextureValidationSeverity.Error);
    public int WarningCount => _issues.Count(issue => issue.Severity == TextureValidationSeverity.Warning);
    public bool IsValid => ErrorCount == 0;
    public bool IsClean => ErrorCount == 0 && WarningCount == 0;
    public IReadOnlyList<TextureValidationIssue> Issues => _issues;

    public string ToMarkdown()
    {
        StringBuilder output = new();
        output.AppendLine("# Procedural texture validation");
        output.AppendLine();
        output.AppendLine("Generated by `res://tests/TextureAtlasValidation.tscn` using the live C# block and item registries.");
        output.AppendLine();
        output.AppendLine("## Summary");
        output.AppendLine();
        output.AppendLine("| Check | Result |");
        output.AppendLine("|---|---:|");
        output.AppendLine($"| Status | {(IsClean ? "PASS" : IsValid ? "PASS WITH WARNINGS" : "FAIL")} |");
        output.AppendLine($"| Atlas | {AtlasWidth} × {AtlasHeight}px |");
        output.AppendLine($"| Tile layout | {AtlasColumns} × {AtlasColumns} tiles, {TilePixels}px each ({TileCount} slots) |");
        output.AppendLine($"| Referenced tiles | {ReferencedTiles} unique |");
        output.AppendLine($"| Painted tiles | {PaintedTiles} |");
        output.AppendLine($"| Painted but unreferenced | {OrphanedPaintedTiles} |");
        output.AppendLine($"| Placeable item mappings | {PlaceableItems} |");
        output.AppendLine($"| Greedy texture-array | {TileArrayLayers} layers; isolated mipmaps: {(TileArrayHasMipmaps ? "yes" : "no")} |");
        output.AppendLine($"| Errors / warnings | {ErrorCount} / {WarningCount} |");
        output.AppendLine();
        output.AppendLine("The packed atlas intentionally uses nearest sampling without atlas mipmaps. The greedy texture-array path generates mipmaps from each isolated tile, preventing neighbouring atlas cells from bleeding into distant surfaces.");
        output.AppendLine();
        output.AppendLine("## Issues");
        output.AppendLine();
        if (_issues.Count == 0)
        {
            output.AppendLine("No missing tiles, invalid references, unexpected duplicate mappings, or renderer-layout issues were found.");
        }
        else
        {
            output.AppendLine("| Severity | Code | Detail |");
            output.AppendLine("|---|---|---|");
            foreach (TextureValidationIssue issue in _issues)
            {
                output.AppendLine($"| {issue.Severity} | `{Escape(issue.Code)}` | {Escape(issue.Message)} |");
            }
        }

        output.AppendLine();
        output.AppendLine("## Block face mappings");
        output.AppendLine();
        output.AppendLine("Face order is +Y, -Y, +X, -X, +Z, -Z. `-1` is allowed only for the non-rendered Air definition.");
        output.AppendLine();
        output.AppendLine("| Block ID | Block | +Y | -Y | +X | -X | +Z | -Z |");
        output.AppendLine("|---:|---|---:|---:|---:|---:|---:|---:|");
        foreach (AtlasBlockMapping block in _blocks)
        {
            output.AppendLine($"| {(byte)block.Id} | {Escape(block.Name)} | {string.Join(" | ", block.FaceTiles)} |");
        }

        output.AppendLine();
        output.AppendLine("## Atlas tile inventory");
        output.AppendLine();
        output.AppendLine("Only tiles referenced by at least one registered block face are listed. The reference column identifies each owning block and face; repeated use within a block is not treated as an accidental duplicate.");
        output.AppendLine();
        output.AppendLine("| Tile | References | Visible pixels | Owners |");
        output.AppendLine("|---:|---:|---:|---|");
        foreach (TextureAtlasTileSummary tile in _tiles)
        {
            if (tile.ReferenceCount == 0)
                continue;

            output.AppendLine($"| {tile.Tile} | {tile.ReferenceCount} | {tile.VisiblePixels}/{TilePixels * TilePixels} | {Escape(string.Join(", ", tile.Owners))} |");
        }

        output.AppendLine();
        output.AppendLine("## Placeable item icon mappings");
        output.AppendLine();
        output.AppendLine("| Item ID | Item | Block | Atlas icon |");
        output.AppendLine("|---:|---|---|---:|");
        foreach (AtlasItemMapping item in _items)
        {
            string blockName = item.Block is { } block && BlockDb.IsDefined(block)
                    ? $"{BlockDb.NameOf(block)} ({(byte)block})"
                    : "MISSING";
            int iconTile = item.Block is { } mapped && BlockDb.IsDefined(mapped)
                    ? BlockDb.IconTile(mapped)
                    : -1;
            output.AppendLine($"| {(byte)item.Id} | {item.Id} | {Escape(blockName)} | {iconTile} |");
        }

        output.AppendLine();
        output.AppendLine("## Close / distant consistency");
        output.AppendLine();
        output.AppendLine("- Source tiles remain 32 × 32 RGBA pixels in the existing 16 × 16 packed atlas.");
        output.AppendLine("- Packed-atlas UV coordinates and AtlasTexture regions are not rewritten by validation.");
        output.AppendLine("- Greedy terrain retains one texture-array layer per atlas slot and per-layer mip generation.");
        output.AppendLine("- No runtime scene node, periodic scan, texture rebuild, voxel mutation, save change, or generator change is introduced.");
        output.AppendLine();
        return output.ToString();
    }

    private static string Escape(string value) =>
            value.Replace("|", "\\|", StringComparison.Ordinal)
                    .Replace("\r", " ", StringComparison.Ordinal)
                    .Replace("\n", " ", StringComparison.Ordinal);
}

/// <summary>
/// Explicit, on-demand checks for the procedural block atlas and its consumers.
/// The validator reads the already-lazy atlas and tile array; it never rebuilds
/// either resource and does not run on gameplay frames.
/// </summary>
public static class TextureAtlasValidator
{
    private const int LegacyPlankBuildingTile = 46;

    private static readonly string[] FaceNames = ["+Y", "-Y", "+X", "-X", "+Z", "-Z"];

    private static readonly (BlockId Id, int FirstFace, int SecondFace, string Reason)[] DistinctFaceRules =
    [
        (BlockId.Grass, 0, 2, "grass cap and side must use their dedicated tiles"),
        (BlockId.SnowGrass, 0, 2, "snow cap and side must use their dedicated tiles"),
        (BlockId.Log, 0, 2, "oak log end grain must remain distinct from bark"),
        (BlockId.BirchLog, 0, 2, "birch log end grain must remain distinct from bark"),
        (BlockId.Planks, 0, 2, "plank end grain must remain distinct from the top"),
        (BlockId.Planks, 0, 4, "plank top must remain distinct from the long-grain side"),
        (BlockId.Planks, 2, 4, "plank end grain must remain distinct from the long-grain side"),
        (BlockId.Cactus, 0, 2, "cactus cap must remain distinct from its ribbed side"),
        (BlockId.CraftingTable, 0, 2, "crafting-table top must remain distinct from its sides"),
        (BlockId.Farmland, 0, 2, "furrowed farmland cap must remain distinct from its side"),
        (BlockId.Bed, 0, 1, "bed top must remain distinct from its fabric side"),
        (BlockId.EnchantingTable, 0, 1, "enchanting-table top must remain distinct from its sides"),
    ];

    private static readonly BlockId[][] ExpectedDuplicateDefinitions =
    [
        [BlockId.Water, BlockId.FlowingWater1, BlockId.FlowingWater2, BlockId.FlowingWater3,
            BlockId.FlowingWater4, BlockId.FlowingWater5, BlockId.FlowingWater6, BlockId.FlowingWater7],
        [BlockId.Planks, BlockId.PlanksSlab, BlockId.PlanksStairs],
        [BlockId.CobblestoneSlab, BlockId.CobblestoneStairs],
        [BlockId.BrickSlab, BlockId.BrickStairs],
    ];

    public static TextureValidationReport ValidateCurrent()
    {
        BlockDb.EnsureTables();
        Image atlas = BlockDb.AtlasTexture().GetImage();
        Texture2DArray tileArray = BlockDb.TileArrayTexture();
        return Analyze(atlas, tileArray, BlockDb.AtlasCols, BlockDb.TilePx,
                GetCurrentBlockMappings(), GetCurrentItemMappings());
    }

    internal static List<AtlasBlockMapping> GetCurrentBlockMappings()
    {
        List<AtlasBlockMapping> result = [];
        foreach (BlockId id in Enum.GetValues<BlockId>())
        {
            if (BlockDb.IsDefined(id))
                result.Add(new AtlasBlockMapping(id, BlockDb.NameOf(id), BlockDb.DefOf(id).Tiles));
        }

        return result;
    }

    internal static List<AtlasItemMapping> GetCurrentItemMappings()
    {
        List<AtlasItemMapping> result = [];
        foreach (ItemId id in ItemDb.Placeable)
        {
            BlockId? block = ItemDb.BlockFor(id);
            Texture2D icon = ItemDb.Icon(id);
            bool atlasIcon = icon is AtlasTexture;
            Rect2 region = icon is AtlasTexture atlasTexture ? atlasTexture.Region : new Rect2();
            bool roundTrips = block is { } mapped && BlockDb.IsDefined(mapped)
                    && ItemDb.BlockItem(mapped) == id;
            result.Add(new AtlasItemMapping(id, block, atlasIcon, region, roundTrips));
        }

        return result;
    }

    internal static TextureValidationReport Analyze(
            Image atlas, Texture2DArray? tileArray, int atlasColumns, int tilePixels,
            IReadOnlyList<AtlasBlockMapping> blocks, IReadOnlyList<AtlasItemMapping>? items)
    {
        List<TextureValidationIssue> issues = [];
        int tileCount = atlasColumns > 0 ? atlasColumns * atlasColumns : 0;
        int atlasWidth = atlas.IsEmpty() ? 0 : atlas.GetWidth();
        int atlasHeight = atlas.IsEmpty() ? 0 : atlas.GetHeight();
        int[] referenceCounts = new int[tileCount];
        List<string>?[] owners = new List<string>?[tileCount];
        List<(int Tile, int VisiblePixels)> summaries = [];
        HashSet<BlockId> seenBlocks = [];

        void Add(TextureValidationSeverity severity, string code, string message) =>
                issues.Add(new TextureValidationIssue(severity, code, message));

        if (atlasColumns <= 0 || tilePixels <= 0)
        {
            Add(TextureValidationSeverity.Error, "atlas.layout.invalid",
                    $"Atlas grid dimensions must be positive (columns={atlasColumns}, tilePixels={tilePixels}).");
        }

        if (!atlas.IsEmpty() && atlas.GetFormat() != Image.Format.Rgba8)
            Add(TextureValidationSeverity.Error, "atlas.format.invalid",
                    $"Procedural atlas format is {atlas.GetFormat()}; expected RGBA8 for consistent alpha coverage and texture-array slicing.");

        bool dimensionsValid = atlasColumns > 0 && tilePixels > 0
                && atlasWidth == atlasColumns * tilePixels
                && atlasHeight == atlasColumns * tilePixels;
        if (!dimensionsValid)
        {
            Add(TextureValidationSeverity.Error, "atlas.dimensions.invalid",
                    $"Expected a square {atlasColumns * tilePixels}px atlas, got {atlasWidth} × {atlasHeight}px.");
        }

        foreach (AtlasBlockMapping block in blocks)
        {
            if (!BlockDb.IsDefined(block.Id))
                Add(TextureValidationSeverity.Error, "mapping.block.invalid-id",
                        $"{block.Name} uses unregistered BlockId {(byte)block.Id}.");

            if (!seenBlocks.Add(block.Id))
                Add(TextureValidationSeverity.Error, "mapping.block.duplicate-id",
                        $"Block ID {(byte)block.Id} ({block.Name}) appears more than once in the material registry.");

            if (block.FaceTiles == null || block.FaceTiles.Length != 6)
            {
                Add(TextureValidationSeverity.Error, "mapping.face-count.invalid",
                        $"{block.Name} ({(byte)block.Id}) must provide exactly six face tile entries.");
                continue;
            }

            for (int face = 0; face < 6; face++)
            {
                int tile = block.FaceTiles[face];
                if (tile == -1 && block.Id == BlockId.Air)
                    continue;
                if (tile < 0 || tile >= tileCount)
                {
                    Add(TextureValidationSeverity.Error, "mapping.tile.invalid",
                            $"{block.Name} ({(byte)block.Id}) face {FaceNames[face]} references tile {tile}; valid rendered tiles are 0..{tileCount - 1}.");
                    continue;
                }

                referenceCounts[tile]++;
                owners[tile] ??= [];
                owners[tile]!.Add($"{block.Name} {FaceNames[face]}");
            }

            if (block.Id == BlockId.Air && block.FaceTiles.Any(tile => tile != -1))
                Add(TextureValidationSeverity.Error, "mapping.air.has-surface",
                        "Air must not reference atlas tiles because it has no rendered surface.");
            if (block.Id != BlockId.Air && block.FaceTiles.Any(tile => tile == -1))
                Add(TextureValidationSeverity.Error, "mapping.face.missing",
                        $"{block.Name} ({(byte)block.Id}) contains a missing face tile (-1).");
        }

        foreach ((BlockId id, int firstFace, int secondFace, string reason) in DistinctFaceRules)
        {
            AtlasBlockMapping? block = blocks.FirstOrDefault(entry => entry.Id == id);
            if (block is not { } mapping || mapping.FaceTiles == null || mapping.FaceTiles.Length != 6)
                continue;
            if (mapping.FaceTiles[firstFace] >= 0 && mapping.FaceTiles[secondFace] >= 0
                    && mapping.FaceTiles[firstFace] == mapping.FaceTiles[secondFace])
            {
                Add(TextureValidationSeverity.Warning, "mapping.directional-faces.collapsed",
                        $"{mapping.Name}: {reason} (both resolve to tile {mapping.FaceTiles[firstFace]}).");
            }
        }

        AddUnexpectedDuplicateDefinitions(blocks, Add);

        int paintedTiles = 0;
        int orphanedPaintedTiles = 0;
        HashSet<int> referenced = [];
        for (int tile = 0; tile < tileCount; tile++)
        {
            if (!dimensionsValid || atlas.IsEmpty())
                continue;

            int originX = tile % atlasColumns * tilePixels;
            int originY = tile / atlasColumns * tilePixels;
            int visiblePixels = 0;
            for (int y = 0; y < tilePixels; y++)
            {
                for (int x = 0; x < tilePixels; x++)
                {
                    if (atlas.GetPixel(originX + x, originY + y).A > 0.01f)
                        visiblePixels++;
                }
            }

            summaries.Add((tile, visiblePixels));
            if (visiblePixels > 0)
                paintedTiles++;

            if (referenceCounts[tile] > 0)
            {
                referenced.Add(tile);
                if (visiblePixels == 0)
                    Add(TextureValidationSeverity.Error, "atlas.tile.unpainted",
                            $"Referenced tile {tile} has no non-transparent pixels; its procedural paint step is missing or blank.");
            }
            else if (visiblePixels > 0)
            {
                orphanedPaintedTiles++;
                if (tile == LegacyPlankBuildingTile)
                {
                    Add(TextureValidationSeverity.Info, "atlas.tile.legacy-orphan",
                            "Tile 46 is the retained legacy plank-building sample. Directional plank tiles 49–51 replaced its live block mapping; the old coordinate remains reserved and untouched.");
                }
                else
                {
                    Add(TextureValidationSeverity.Warning, "atlas.tile.unreferenced",
                            $"Tile {tile} contains painted pixels but no registered block face references it.");
                }
            }
        }

        AddDuplicatePixelTiles(atlas, atlasColumns, tilePixels, dimensionsValid, Add);

        if (tileArray != null)
        {
            if (tileArray.GetLayers() != tileCount)
                Add(TextureValidationSeverity.Error, "array.layer-count.invalid",
                        $"Greedy texture-array has {tileArray.GetLayers()} layers; expected one layer for each of {tileCount} atlas slots.");
            if (tileArray.GetWidth() != tilePixels || tileArray.GetHeight() != tilePixels)
                Add(TextureValidationSeverity.Error, "array.layer-size.invalid",
                        $"Greedy texture-array layers are {tileArray.GetWidth()} × {tileArray.GetHeight}px; expected {tilePixels} × {tilePixels}px.");
            if (!tileArray.HasMipmaps())
                Add(TextureValidationSeverity.Error, "array.mipmaps.missing",
                        "Greedy texture-array has no mipmaps; distant surfaces may shimmer. Generate mipmaps from isolated tiles, not the packed atlas.");
        }
        else
        {
            Add(TextureValidationSeverity.Warning, "array.missing",
                    "No greedy texture-array resource was supplied for validation.");
        }

        int placeableCount = 0;
        if (items != null)
        {
            foreach (AtlasItemMapping item in items)
            {
                placeableCount++;
                if (item.Block is not { } blockId || !blocks.Any(block => block.Id == blockId))
                {
                    Add(TextureValidationSeverity.Error, "item.block.invalid",
                            $"Placeable item {item.Id} has no registered block mapping.");
                    continue;
                }

                AtlasBlockMapping mapping = blocks.First(block => block.Id == blockId);
                int iconTile = mapping.FaceTiles.Length == 6
                        ? (mapping.FaceTiles[4] >= 0 ? mapping.FaceTiles[4] : mapping.FaceTiles[0])
                        : -1;
                if (!item.RoundTrips)
                    Add(TextureValidationSeverity.Error, "item.block.round-trip",
                            $"Placeable item {item.Id} does not round-trip through BlockFor / BlockItem for {blockId}.");
                if (!item.UsesAtlasIcon)
                    Add(TextureValidationSeverity.Error, "item.icon.not-atlas-backed",
                            $"Placeable item {item.Id} no longer uses the shared AtlasTexture path.");
                if (iconTile < 0 || iconTile >= tileCount)
                {
                    Add(TextureValidationSeverity.Error, "item.icon.tile.invalid",
                            $"Placeable item {item.Id} resolves to invalid icon tile {iconTile}.");
                    continue;
                }

                Rect2 expectedRegion = new(
                        iconTile % atlasColumns * tilePixels,
                        iconTile / atlasColumns * tilePixels,
                        tilePixels, tilePixels);
                if (item.IconRegion != expectedRegion)
                    Add(TextureValidationSeverity.Error, "item.icon.region.invalid",
                            $"Placeable item {item.Id} icon region {item.IconRegion} does not match block {blockId}'s atlas tile {iconTile}.");
            }
        }

        List<TextureAtlasTileSummary> tileSummaries = [];
        foreach ((int tile, int visiblePixels) in summaries)
        {
            tileSummaries.Add(new TextureAtlasTileSummary(
                    tile, referenceCounts[tile], visiblePixels, owners[tile] ?? []));
        }
        return new TextureValidationReport(
                atlasColumns, tilePixels, atlasWidth, atlasHeight, referenced.Count,
                paintedTiles, orphanedPaintedTiles, placeableCount,
                tileArray?.GetLayers() ?? 0, tileArray?.HasMipmaps() ?? false, issues,
                blocks.ToList(), items?.ToList() ?? [], tileSummaries);
    }

    private static void AddUnexpectedDuplicateDefinitions(
            IReadOnlyList<AtlasBlockMapping> blocks,
            Action<TextureValidationSeverity, string, string> add)
    {
        Dictionary<string, List<BlockId>> signatures = new(StringComparer.Ordinal);
        foreach (AtlasBlockMapping block in blocks)
        {
            if (block.FaceTiles == null || block.FaceTiles.Length != 6)
                continue;
            string signature = string.Join(",", block.FaceTiles);
            if (!signatures.TryGetValue(signature, out List<BlockId>? owners))
            {
                owners = [];
                signatures.Add(signature, owners);
            }
            owners.Add(block.Id);
        }

        foreach (List<BlockId> owners in signatures.Values)
        {
            if (owners.Count < 2 || IsExpectedDuplicateGroup(owners))
                continue;
            string names = string.Join(", ", owners.Select(id =>
                    blocks.First(block => block.Id == id).Name));
            add(TextureValidationSeverity.Warning, "mapping.definition.duplicate",
                    $"Blocks {names} have identical six-face tile mappings. Confirm this is an intentional shared material definition.");
        }
    }

    private static bool IsExpectedDuplicateGroup(List<BlockId> ids)
    {
        foreach (BlockId[] expected in ExpectedDuplicateDefinitions)
        {
            if (ids.Count == expected.Length && ids.All(expected.Contains))
                return true;
        }
        return false;
    }

    private static void AddDuplicatePixelTiles(
            Image atlas, int atlasColumns, int tilePixels, bool dimensionsValid,
            Action<TextureValidationSeverity, string, string> add)
    {
        if (!dimensionsValid)
            return;

        Dictionary<ulong, List<int>> buckets = [];
        for (int tile = 0; tile < atlasColumns * atlasColumns; tile++)
        {
            int originX = tile % atlasColumns * tilePixels;
            int originY = tile / atlasColumns * tilePixels;
            bool painted = false;
            for (int y = 0; y < tilePixels && !painted; y++)
            {
                for (int x = 0; x < tilePixels; x++)
                {
                    if (atlas.GetPixel(originX + x, originY + y).A > 0.01f)
                    {
                        painted = true;
                        break;
                    }
                }
            }
            if (!painted)
                continue;

            ulong hash = HashTile(atlas, tile, atlasColumns, tilePixels);
            if (!buckets.TryGetValue(hash, out List<int>? candidates))
            {
                candidates = [];
                buckets.Add(hash, candidates);
                candidates.Add(tile);
                continue;
            }

            foreach (int candidate in candidates)
            {
                if (TilesEqual(atlas, candidate, tile, atlasColumns, tilePixels))
                {
                    add(TextureValidationSeverity.Warning, "atlas.tile.duplicate-pixels",
                            $"Atlas tiles {candidate} and {tile} contain identical RGBA pixels. Keep one canonical tile or document the intentional duplicate.");
                    break;
                }
            }
            candidates.Add(tile);
        }
    }

    private static ulong HashTile(Image atlas, int tile, int atlasColumns, int tilePixels)
    {
        const ulong offset = 14695981039346656037UL;
        const ulong prime = 1099511628211UL;
        ulong hash = offset;
        int originX = tile % atlasColumns * tilePixels;
        int originY = tile / atlasColumns * tilePixels;
        for (int y = 0; y < tilePixels; y++)
        {
            for (int x = 0; x < tilePixels; x++)
            {
                Color color = atlas.GetPixel(originX + x, originY + y);
                hash = (hash ^ Quantize(color.R)) * prime;
                hash = (hash ^ Quantize(color.G)) * prime;
                hash = (hash ^ Quantize(color.B)) * prime;
                hash = (hash ^ Quantize(color.A)) * prime;
            }
        }
        return hash;
    }

    private static byte Quantize(float channel) =>
            (byte)Math.Clamp((int)MathF.Round(channel * 255.0f), 0, 255);

    private static bool TilesEqual(Image atlas, int first, int second, int atlasColumns, int tilePixels)
    {
        int firstX = first % atlasColumns * tilePixels;
        int firstY = first / atlasColumns * tilePixels;
        int secondX = second % atlasColumns * tilePixels;
        int secondY = second / atlasColumns * tilePixels;
        for (int y = 0; y < tilePixels; y++)
        {
            for (int x = 0; x < tilePixels; x++)
            {
                if (atlas.GetPixel(firstX + x, firstY + y) != atlas.GetPixel(secondX + x, secondY + y))
                    return false;
            }
        }
        return true;
    }
}

internal sealed record TextureAtlasTileSummary(
        int Tile, int ReferenceCount, int VisiblePixels, IReadOnlyList<string> Owners);
